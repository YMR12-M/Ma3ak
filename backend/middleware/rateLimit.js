/* ============================================
   MA3ak (معاك) - حدود المحاولات (حماية من التخمين بالجملة)

   ملحوظة مهمة: الحدود دي بتعتمد على IP المستخدم الحقيقي، وده بيتوقف على
   app.set('trust proxy', 1) في server.js. من غيره كل المستخدمين ورا بروكسي
   Render بيبانوا كأنهم شخص واحد، فمحاولات حد فاشلة كانت بتقفل الدخول على الكل.
   ============================================ */

const { rateLimit, ipKeyGenerator } = require('express-rate-limit');

const common = {
  standardHeaders: true,
  legacyHeaders: false,
};

/* تسجيل الدخول بكلمة مرور - الهدف إبطاء تجربة كلمات المرور بالجملة.
   منفصل عن حد لينك المريض عمدًا: قبل كده كانوا بيتشاركوا نفس العدّاد، يعني
   10 محاولات دخول فاشلة كانت بتمنع المرضى كمان من الدخول بلينكاتهم - وهم
   أصلاً مالهمش أي علاقة بكلمة المرور. */
const loginLimiter = rateLimit({
  ...common,
  windowMs: 15 * 60 * 1000, // 15 دقيقة
  limit: 10,
  message: { error: 'محاولات كتير في وقت قصير، جرب تاني بعد شوية' },
});

/* دخول المريض بلينك - عدّاد مستقل بحد أوسع شوية، لأن ده الطريق الوحيد للمريض
   إنه يدخل التطبيق أصلاً (مفيش عنده كلمة مرور يرجع لها لو اتحظر بالغلط). */
const accessLimiter = rateLimit({
  ...common,
  windowMs: 15 * 60 * 1000,
  limit: 20,
  message: { error: 'محاولات كتير في وقت قصير، جرب تاني بعد شوية' },
});

// أقل صرامة، بس بيمنع تسجيل حسابات بالجملة من IP واحد
const registerLimiter = rateLimit({
  ...common,
  windowMs: 60 * 60 * 1000, // ساعة
  limit: 20,
  message: { error: 'محاولات تسجيل كتير في وقت قصير، جرب تاني بعد شوية' },
});

/* الانضمام لمريض بكود مشاركة - ده كان مفتوح على الآخر من غير أي حد، يعني
   حد يقدر يجرب آلاف الأكواد في الثانية لحد ما يوصل لكود شغال، وياخد وصول
   كامل لبيانات مريض طبية ويعدّل أدويته.

   بنحسب الحد على حساب المستخدم نفسه (req.user.id) مش على الـ IP: المهاجم
   لازم يكون مسجّل دخول عشان يستخدم المسار ده أصلاً، وتغيير الـ IP مش هيهرّبه
   من العدّاد. المستخدم العادي بيستخدم الكود ده مرة أو مرتين في عمره كله،
   فـ 10 محاولات في الساعة مش هتزعج حد حقيقي.

   ipKeyGenerator بييجي من المكتبة نفسها وبيوحّد عناوين IPv6 على مستوى الشبكة
   (/64) - من غيره المهاجم على IPv6 يقدر يغيّر آخر جزء من عنوانه ويعدي من الحد
   كأنه مستخدم جديد كل مرة. (المسار محمي بـ authRequired فـ req.user موجود دايمًا،
   والـ fallback هنا احتياط لو الترتيب اتغير يومًا.) */
const linkPatientLimiter = rateLimit({
  ...common,
  windowMs: 60 * 60 * 1000, // ساعة
  limit: 10,
  keyGenerator: (req) => (req.user ? `user:${req.user.id}` : ipKeyGenerator(req.ip)),
  message: { error: 'حاولت تنضم بكود غلط مرات كتير، استنى شوية وجرب تاني' },
});

module.exports = { loginLimiter, accessLimiter, registerLimiter, linkPatientLimiter };
