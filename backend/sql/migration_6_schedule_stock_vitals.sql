USE ma3ak;

-- ---------- 1) أيام الأسبوع: الدواء مبقاش يومي إجباري ----------
-- قبل كده كل دواء في التطبيق كان **يومي بالضرورة**: times مصفوفة مواعيد،
-- والـ scheduler بيولّد لكل ميعاد فيها كل يوم. يعني أدوية أسبوعية شائعة جدًا
-- عند نفس الجمهور ده (أليندرونات للعظام، ميثوتريكسات للروماتيزم، حقن ب12)
-- مكانش ينفع تتسجّل صح خالص - يا يومي فالمريض يترنّ عليه كل يوم وتتحسب فايتة
-- 6 مرات في الأسبوع، يا ميتسجّلش أصلاً.
--
-- قناع 7 بت: بت 0 = الأحد ... بت 6 = السبت. 127 = كل الأيام (السلوك القديم
-- بالظبط)، فكل الأدوية الموجودة مش هتتأثر.
ALTER TABLE medications
  ADD COLUMN days_of_week TINYINT UNSIGNED NOT NULL DEFAULT 127 AFTER times;

-- ---------- 2) كمية الدوا ----------
-- "الدوا خلص" كان بلاغ **رجعي**: بيتبعت بعد ما الدوا يخلص فعلاً، والمتابع
-- ساعتها ممكن يحتاج يوم أو اتنين يجيبه - وكبير السن يقعد الأيام دي من غير
-- دوا ضغط أو قلب. التطبيق عارف عدد الجرعات اليومية بالظبط، فحساب "فاضل كام
-- يوم" تقريبًا مجاني.
--
-- NULL = المتابع مش بيتابع الكمية للدوا ده (الافتراضي - مفيش أي تغيير سلوك).
ALTER TABLE medications
  ADD COLUMN pills_left SMALLINT UNSIGNED NULL AFTER days_of_week,
  -- طابع "اتبعت مرة واحدة": من غيره تنبيه قرب الخلاص يتبعت كل يوم لحد ما
  -- المتابع يجيب الدوا. بيترجّع NULL أول ما الكمية تتزوّد (المتابع جاب عبوة).
  ADD COLUMN low_stock_notified_at DATETIME NULL AFTER pills_left;

-- ---------- 3) الغفوة بقت بتمدّ فترة السماح فعليًا ----------
-- قبل كده الغفوة كانت **بتأجّل الرنّة بس** من غير ما تأجّل حساب "فاتت":
-- notifyDueDoses كانت بتصفّي snooze_until = NULL بعد الرنّة، وفي نفس الدورة
-- markMissedAndNotify بتشوف الصف (scheduled_at عدّى فترة السماح) وتعلّمه فايت.
-- النتيجة: موبايل المريض بيقوله "وقت الدوا" وموبايل ابنه بيقوله "فوّتها" في
-- نفس الدقيقة. (و 3 غفوات × 10 د = 30 د = GRACE_MINUTES بالظبط، فالرقمين
-- كانوا متعارضين من الأساس.)
--
-- الحل: snooze_until مبقاش يتصفّى - بقى هو "الميعاد الفعلي" اللي كل مراحل
-- المنبه بتتحسب منه (COALESCE(snooze_until, scheduled_at)). والعمود ده بيسجّل
-- إننا رنّينا لغفوة معيّنة، بدل ما التصفية هي اللي تمنع تكرار الرنّة.
ALTER TABLE doses
  ADD COLUMN snooze_notified_at DATETIME NULL AFTER snooze_count;

-- ---------- 4) فهارس كانت ناقصة ----------
-- الـ scheduler بيقرا المواعيد الجاية **كل دقيقة**، ومن غير الفهرس ده الاستعلام
-- بيمسح الجدول كله في كل دورة.
ALTER TABLE appointments
  ADD KEY idx_appointment_at (appointment_at);

-- شاشة القياسات بتقرا آخر 100 قراءة لمريض مرتّبة بالوقت - من غير الفهرس ده
-- الاستعلام بيعمل filesort على كل قراءات المريض.
ALTER TABLE vitals
  ADD KEY idx_patient_recorded (patient_id, recorded_at);
